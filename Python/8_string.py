# In Python, a string is a contiguous sequence of Unicode characters used to represent text-based information. 
# Handled by the built-in str class, strings can include letters, numbers, symbols, spaces, and even emojis. 
# Unlike languages like Java or C++, Python does not have a distinct character type; 
# a single character is simply treated as a string of length one.

#  Strings are immutable, meaning their elements cannot be altered or replaced in place after creation.
#  Modifying a string always creates a brand-new string object.

single_quote_str = 'Hello'
double_quote_str = "World"
multiline_str = """This string
spans multiple lines."""
print(single_quote_str) 
print(double_quote_str) 
print(multiline_str) 
