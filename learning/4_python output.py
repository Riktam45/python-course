# Print Without a New Line
# By default, the print() function ends with a new line.
# If printing multiple words on the same line, use the end = " " parameter

print("Hello", end=" ")
print("World!")

# Python Output Numbers
print(3)
print(358)
print(50000)

# math inside the print() function
print(3 + 3)
print(2 * 5)

# Mix Text and Numbers
print("I am", 23, "years old.")