#Print all key names in the dictionary, one by one:
cars = {
    "brand": "Audi",
    "model": "A6",
    "color": "Red"  
}
for x in cars:
    print(x)

#Print all values in the dictionary, one by one
cars1 = {
    "brand": "BMW",
    "model": "M4",
    "color": "Blue"  
}
for x in cars1:
    print(cars1[x])